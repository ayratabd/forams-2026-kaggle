import os
import glob
import torch
import numpy as np
from torch.utils.data import Dataset, DataLoader
import pytorch_lightning as pl

class ForamsDataset(Dataset):
    def __init__(self, data_dir, is_train=True, transform=None):
        """
        Args:
            data_dir (str): Path to directory containing npz synthetic chunks.
            is_train (bool): True for training set, False for validation.
        """
        self.data_dir = data_dir
        self.is_train = is_train
        self.transform = transform
        
        # In the hybrid approach, we will load synthetic data generated by the 2nd-place engine.
        self.files = glob.glob(os.path.join(data_dir, "*.npz"))
        
    def __len__(self):
        return len(self.files)

    def __getitem__(self, idx):
        # Load the synthetic chunk
        file_path = self.files[idx]
        data = np.load(file_path)
        
        image = data["image"]  # shape: (D, H, W)
        classes = data["classes"]  # class labels

        
        # The 2.5D DINOv2 approach extracts adjacent slices per channel.
        # DINOv2 expects 3-channel input [3, H, W].
        # We will extract the middle 3 slices along the D axis.
        mid = image.shape[0] // 2
        
        # Ensure we have at least 3 slices, otherwise pad
        if image.shape[0] >= 3:
            slices = image[mid-1:mid+2, :, :]
        else:
            slices = np.zeros((3, image.shape[1], image.shape[2]), dtype=image.dtype)
            slices[:image.shape[0], :, :] = image
            
        # Convert to tensor [3, H, W]
        image_tensor = torch.from_numpy(slices).float()
        
        # DINOv2 expects 224x224 input, so we use interpolate.
        # interpolate expects [B, C, H, W], so we add a batch dimension temporarily
        image_tensor = torch.nn.functional.interpolate(
            image_tensor.unsqueeze(0), size=(224, 224), mode="bilinear", align_corners=False
        ).squeeze(0)
        
        # Normalize to [0, 1] as a basic preprocessing step
        if image_tensor.max() > 0:
            image_tensor = image_tensor / image_tensor.max()
            
        # For CenterNet, the network will output a heatmap of size 64x64
        # Our original input is shape (D, H_orig, W_orig) -> (275, 138, 138)
        H_orig, W_orig = image.shape[1], image.shape[2]
        H_out, W_out = 64, 64
        
        heatmap = np.zeros((14, H_out, W_out), dtype=np.float32)
        offset_map = np.zeros((2, H_out, W_out), dtype=np.float32)
        offset_mask = np.zeros((H_out, W_out), dtype=np.float32)
        
        centers = data["centers"]
        radii = data["radii"]
        classes = data["classes"]
        
        # Filter active centers for this slice
        active_indices = np.abs(centers[:, 0] - mid) <= radii
        
        for center, radius, cls in zip(centers[active_indices], radii[active_indices], classes[active_indices]):
            z, y, x = center[0], center[1], center[2]
            
            # Map coordinates directly from original to heatmap
            x_out = (x / W_orig) * W_out
            y_out = (y / H_orig) * H_out
            
            # Integer coordinates on heatmap
            x_int = int(x_out)
            y_int = int(y_out)
            
            if 0 <= x_int < W_out and 0 <= y_int < H_out:
                # Subpixel offset
                offset_map[0, y_int, x_int] = x_out - x_int
                offset_map[1, y_int, x_int] = y_out - y_int
                offset_mask[y_int, x_int] = 1.0
                
                # Draw Gaussian on heatmap
                # Calculate apparent 2D radius at this depth
                dz = abs(z - mid)
                r_2d = np.sqrt(max(0, radius**2 - dz**2))
                
                # Scale radius to heatmap dimensions
                r_out = (r_2d / W_orig) * W_out
                
                # Sigma is commonly set as radius / 3 so 99% of mass falls in radius
                sigma = max(r_out / 3.0, 1.0)
                
                # Create coordinate grid
                Y, X = np.ogrid[0:H_out, 0:W_out]
                dist = (X - x_int)**2 + (Y - y_int)**2
                
                # Generate unnormalized Gaussian
                gaussian = np.exp(-dist / (2 * sigma**2))
                
                # Merge with existing heatmap by taking maximum (standard CenterNet logic)
                heatmap[cls] = np.maximum(heatmap[cls], gaussian)
                
        targets = {
            "heatmap": torch.from_numpy(heatmap),
            "offset": torch.from_numpy(offset_map),
            "mask": torch.from_numpy(offset_mask)
        }
        
        return image_tensor, targets


class ForamsDataModule(pl.LightningDataModule):
    def __init__(self, data_dir="data/synthetic", batch_size=4, num_workers=4):
        super().__init__()
        self.data_dir = data_dir
        self.batch_size = batch_size
        self.num_workers = num_workers

    def setup(self, stage=None):
        train_dir = os.path.join(self.data_dir, "train")
        val_dir = os.path.join(self.data_dir, "validation")
        
        self.train_dataset = ForamsDataset(train_dir, is_train=True)
        self.val_dataset = ForamsDataset(val_dir, is_train=False)

    def train_dataloader(self):
        return DataLoader(
            self.train_dataset,
            batch_size=self.batch_size,
            shuffle=True,
            num_workers=self.num_workers,
            pin_memory=True
        )

    def val_dataloader(self):
        return DataLoader(
            self.val_dataset,
            batch_size=self.batch_size,
            shuffle=False,
            num_workers=self.num_workers,
            pin_memory=True
        )
